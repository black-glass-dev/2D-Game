#!/usr/bin/env python3
"""Generate/check the packaged GDScript localization catalog from its CSV source.

Godot can scan the CSV while running from a loose source tree, but Android export
may omit a file only opened through FileAccess. The generated script is imported
by the LocalizationService, so every player-facing translation is guaranteed to
be present in the exported pack. The CSV remains the readable source of truth.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG_RELATIVE_PATH = Path("data/localization/redline.csv")
OUTPUT_RELATIVE_PATH = Path("data/localization/redline_catalog.gd")


def gd_quote(value: str) -> str:
    """Return a Godot double-quoted string literal for plain catalog text."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def load_catalog(root: Path = ROOT) -> tuple[list[str], list[tuple[str, list[str]]]]:
    with (root / CATALOG_RELATIVE_PATH).open(encoding="utf-8", newline="") as stream:
        rows = list(csv.reader(stream))
    if not rows or rows[0] != ["keys", "en", "bn"]:
        raise ValueError("expected CSV header keys,en,bn")
    entries: list[tuple[str, list[str]]] = []
    seen: set[str] = set()
    for row_number, row in enumerate(rows[1:], start=2):
        if len(row) != 3 or not all(field.strip() for field in row):
            raise ValueError(f"row {row_number} must contain non-empty key, English, and Bengali values")
        key = row[0].strip()
        if key in seen:
            raise ValueError(f"duplicate key at row {row_number}: {key}")
        seen.add(key)
        entries.append((key, [row[1].strip(), row[2].strip()]))
    return ["en", "bn"], entries


def render(root: Path = ROOT) -> str:
    locales, entries = load_catalog(root)
    lines = [
        "# Generated by tools/generate_embedded_localization_catalog.py; do not edit by hand.",
        "# The CSV remains the reviewable source of truth. This script anchors every message",
        "# in an exported PCK/APK so Android cannot lose dynamically-read translation content.",
        "class_name RedlineLocalizationCatalog",
        "extends RefCounted",
        "",
        "const TRANSLATIONS := {",
    ]
    for locale_index, locale in enumerate(locales):
        lines.append(f"\t{gd_quote(locale)}: {{")
        for entry_index, (key, translations) in enumerate(entries):
            comma = "," if entry_index < len(entries) - 1 else ""
            lines.append(f"\t\t{gd_quote(key)}: {gd_quote(translations[locale_index])}{comma}")
        locale_comma = "," if locale_index < len(locales) - 1 else ""
        lines.append(f"\t}}{locale_comma}")
    lines.extend(
        [
            "}",
            "",
            "static func build_translations() -> Dictionary:",
            "\tvar translations: Dictionary = {}",
            "\tfor locale in TRANSLATIONS:",
            "\t\tvar translation := Translation.new()",
            "\t\ttranslation.locale = locale",
            "\t\tfor key in TRANSLATIONS[locale]:",
            "\t\t\ttranslation.add_message(key, TRANSLATIONS[locale][key])",
            "\t\ttranslations[locale] = translation",
            "\treturn translations",
            "",
        ]
    )
    return "\n".join(lines)


def check(root: Path = ROOT) -> tuple[int, tuple[str, ...]]:
    expected = render(root)
    output = root / OUTPUT_RELATIVE_PATH
    actual = output.read_text(encoding="utf-8") if output.is_file() else None
    if actual != expected:
        raise ValueError(f"{OUTPUT_RELATIVE_PATH.as_posix()} is stale; run tools/generate_embedded_localization_catalog.py")
    locales, entries = load_catalog(root)
    return len(entries), tuple(locales)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when the generated catalog is stale")
    args = parser.parse_args(argv)
    try:
        if args.check:
            entries, locales = check()
            print(f"LOCALIZATION_CATALOG_GENERATION_PASS entries={entries} locales={','.join(locales)}")
            return
        expected = render()
        (ROOT / OUTPUT_RELATIVE_PATH).write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT_RELATIVE_PATH} with {len(load_catalog()[1])} keys.")
    except (OSError, ValueError) as exc:
        print(f"LOCALIZATION_CATALOG_GENERATION_ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc


if __name__ == "__main__":
    main()
