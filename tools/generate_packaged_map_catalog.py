#!/usr/bin/env python3
"""Generate/check explicit map-resource export anchors.

MapRegistry still discovers resources from data/maps at runtime. This generated
catalog preloads every committed map resource so Godot's Android exporter includes
the directory-scanned resources in the PCK even though no scene references them
directly.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP_DIRECTORY_RELATIVE_PATH = Path("data/maps")
OUTPUT_RELATIVE_PATH = MAP_DIRECTORY_RELATIVE_PATH / "packaged_map_catalog.gd"
ID_PATTERN = re.compile(r'^id\s*=\s*"([A-Za-z0-9_]+)"\s*$', re.MULTILINE)


def map_resources(root: Path = ROOT) -> list[tuple[str, Path]]:
    map_directory = root / MAP_DIRECTORY_RELATIVE_PATH
    entries: list[tuple[str, Path]] = []
    seen_ids: set[str] = set()
    for path in sorted(map_directory.glob("*.tres")):
        match = ID_PATTERN.search(path.read_text(encoding="utf-8"))
        if match is None:
            raise ValueError(f"{path.relative_to(root)} has no simple id assignment")
        map_id = match.group(1)
        if map_id in seen_ids:
            raise ValueError(f"duplicate map id: {map_id}")
        seen_ids.add(map_id)
        entries.append((map_id, path))
    if not entries:
        raise ValueError("no map resources found")
    return entries


def render(root: Path = ROOT) -> str:
    entries = map_resources(root)
    lines = [
        "# Generated by tools/generate_packaged_map_catalog.py; do not edit by hand.",
        "# MapRegistry still scans data/maps at runtime. These preloads only ensure that",
        "# directory-discovered map resources are embedded in exported PCK/APK builds.",
        "class_name RedlinePackagedMapCatalog",
        "extends RefCounted",
        "",
        "const PACKAGED_MAPS := [",
    ]
    for _map_id, path in entries:
        lines.append(f'\tpreload("res://{path.relative_to(root).as_posix()}"),')
    lines.extend(
        [
            "]",
            "",
            "static func all_maps() -> Array[RedlineMapData]:",
            "\tvar maps: Array[RedlineMapData] = []",
            "\tfor resource in PACKAGED_MAPS:",
            "\t\tvar map_data := resource as RedlineMapData",
            "\t\tif map_data != null:",
            "\t\t\tmaps.append(map_data)",
            "\treturn maps",
            "",
        ]
    )
    return "\n".join(lines)


def check(root: Path = ROOT) -> int:
    expected = render(root)
    output = root / OUTPUT_RELATIVE_PATH
    actual = output.read_text(encoding="utf-8") if output.is_file() else None
    if actual != expected:
        raise ValueError(f"{OUTPUT_RELATIVE_PATH.as_posix()} is stale; run tools/generate_packaged_map_catalog.py")
    return len(map_resources(root))


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when the generated catalog is stale")
    args = parser.parse_args(argv)
    try:
        if args.check:
            print(f"PACKAGED_MAP_CATALOG_PASS maps={check()}")
            return
        expected = render()
        (ROOT / OUTPUT_RELATIVE_PATH).write_text(expected, encoding="utf-8")
        print(f"Wrote {OUTPUT_RELATIVE_PATH} with {len(map_resources())} map resource anchors.")
    except (OSError, ValueError) as exc:
        print(f"PACKAGED_MAP_CATALOG_ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc


if __name__ == "__main__":
    main()
